// Ensure initial data exists in storage
export function ensureInitialized() {
  if (typeof window === 'undefined') return;

  if (localStorage.getItem(STORAGE_CLEAN_VERSION_KEY) !== 'v4_clean_blank_slate') {
    resetAllDataToEmpty();
    return;
  }

  if (!localStorage.getItem(STORAGE_KEYS.SETTINGS)) {
    resetAllDataToEmpty();
  }

  // Tự động quét và dọn dẹp học sinh mẫu tự sinh theo yêu cầu người dùng, giữ nguyên học sinh GVCN upload
  const PURGE_KEY = 'sso_purge_seed_students_completed_v4';
  if (localStorage.getItem(PURGE_KEY) !== 'done') {
    localStorage.setItem(PURGE_KEY, 'done');
    // Phục hồi lại các ID timestamp bị ghi nhầm vào danh sách xóa
    try {
      const rawDel = localStorage.getItem(STORAGE_KEYS.DELETED_STUDENT_IDS);
      if (rawDel) {
        const parsedDel = JSON.parse(rawDel);
        if (Array.isArray(parsedDel)) {
          const cleanedDel = parsedDel.filter((id) => !/^std_1[6-9]\d{10,}/.test(id) && !/^std_2\d{11,}/.test(id));
          localStorage.setItem(STORAGE_KEYS.DELETED_STUDENT_IDS, JSON.stringify(cleanedDel));
        }
      }
    } catch {}

    setTimeout(() => {
      StorageService.purgeAutoGeneratedStudents().catch((e) => {
        console.warn('Initial purge auto-generated students notice:', e);
      });
    }, 50);
  }
}

